// catalogPath is the generated tool catalog linked from the README.
var catalogPath = filepath.Join("..", "..", "docs", "TOOLS.md")

// TestToolCatalog keeps docs/TOOLS.md in sync with the registered tools,
// resources and prompts. Regenerate with: go test ./internal/server -run Catalog -update
func TestToolCatalog(t *testing.T) {
	got := catalog(t)
	if *update {
		if err := os.WriteFile(catalogPath, got, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(catalogPath)
	if err != nil {
		t.Fatalf("%v (run with -update to create)", err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("docs/TOOLS.md is out of date; run: go test ./internal/server -run Catalog -update")
	}
}

func catalog(t *testing.T) []byte {
	t.Helper()
	ctx := context.Background()
	var b bytes.Buffer
	b.WriteString("# Tool catalog\n\n")
	b.WriteString("<!-- Generated by TestToolCatalog in internal/server; do not edit.\n")
	b.WriteString("     Regenerate with: go test ./internal/server -run Catalog -update -->\n\n")
	b.WriteString("Most tools take optional `device` and `vdom` arguments; see each tool's input schema. ")
	b.WriteString("**Access:** `read` tools never change the device; `write` tools are hidden by `-read-only` ")
	b.WriteString("and recorded in the audit log; `confirm` tools also need the device's hostname as `confirm`.\n")

	all := map[string]bool{}
	for _, ts := range tools.Toolsets {
		list := listTools(t, connect(t, tools.Options{Toolsets: []string{ts}, BackupDir: t.TempDir()}))
		fmt.Fprintf(&b, "\n## %s\n\n| Tool | Access | Description |\n|---|---|---|\n", ts)
		for _, tool := range list {
			if tool.Name == "ping" {
				continue
			}
			all[tool.Name] = true
			fmt.Fprintf(&b, "| `%s` | %s | %s |\n", tool.Name, access(tool), cell(firstSentence(tool.Description)))
		}
	}

	cs := connect(t, tools.Options{BackupDir: t.TempDir()})
	b.WriteString("\n## Resources\n\n| URI | Description |\n|---|---|\n")
	res, err := cs.ListResources(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	for _, r := range res.Resources {
		if !strings.Contains(r.URI, "://fw/") { // skip the per-device instances of the templates
			fmt.Fprintf(&b, "| `%s` | %s |\n", r.URI, cell(r.Description))
		}
	}
	templates, err := cs.ListResourceTemplates(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	for _, r := range templates.ResourceTemplates {
		fmt.Fprintf(&b, "| `%s` | %s |\n", r.URITemplate, cell(r.Description))
	}

	b.WriteString("\n## Prompts\n\n| Prompt | Arguments | Description |\n|---|---|---|\n")
	prompts, err := cs.ListPrompts(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	for _, p := range prompts.Prompts {
		var args []string
		for _, a := range p.Arguments {
			if a.Required {
				args = append(args, "`"+a.Name+"`")
			} else {
				args = append(args, "`"+a.Name+"`?")
			}
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", p.Name, strings.Join(args, ", "), cell(p.Description))
	}
	fmt.Fprintf(&b, "\n%d tools in total.\n", len(all))
	return b.Bytes()
}

func access(tool *mcp.Tool) string {
	switch {
	case tool.Annotations != nil && tool.Annotations.ReadOnlyHint:
		return "read"
	case strings.Contains(fmt.Sprint(tool.InputSchema), "confirm"):
		return "confirm"
	default:
		return "write"
	}
}

// firstSentence returns the description up to the first ". " that doesn't
// end an abbreviation such as "e.g.".
func firstSentence(s string) string {
	for i := 0; i < len(s); {
		j := strings.Index(s[i:], ". ")
		if j < 0 {
			break
		}
		end := i + j + 1
		if !strings.HasSuffix(s[:end], "e.g.") && !strings.HasSuffix(s[:end], "i.e.") {
			return s[:end]
		}
		i = end
	}
	return s
}

func cell(s string) string {
	return strings.NewReplacer("|", `\|`, "\n", " ").Replace(s)
}
